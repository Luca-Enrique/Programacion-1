'''
Dada esta lista [10, 20, 30, 40, 50], 
imprimí solo los tres del medio usando slicing.
'''
# Lista de números
listaNumeros = [10, 20, 30, 40, 50]

# Definimos una variable con los números del medio
listaNumerosMedio = listaNumeros [1 : 4]

# Imprimimos en consola la variable con los números del medio
print(f"Los números del medio son : {listaNumerosMedio}.")