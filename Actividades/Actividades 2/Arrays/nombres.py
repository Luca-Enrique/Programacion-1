'''
Creá una lista con 5 nombres. 
Imprimí el primero y el último.
'''

# Lista de 5 nombres
listaNombres = ["Luca", "Facundo", "Verónica", "Rodrigo", "Juan"]

# Guardamos el primer y último índice en variables 
primerNombre = listaNombres[0]
ultimoNombre = listaNombres[-1]

# Imprimimos en pantalla las variables
print(f"Primer nombre: {primerNombre}, último nombre: {ultimoNombre}")
